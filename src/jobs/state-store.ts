import fs from "node:fs";
import path from "node:path";
import { readJsonFile, withFileLock, writeJsonFile } from "../upstream/fs.mjs";
import { pathInWorkspace, PluginError, SecretRedactor } from "../security/index.js";
import { assertTransition, isActive } from "./state-machine.js";
import type { JobRecord, JobState } from "./types.js";

const jobId = /^[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}$/;
const redact = new SecretRedactor();

export class JobStore {
  readonly directory: string;
  readonly jobs: string;

  constructor(readonly root: string, workspaceDirectory: string, private readonly retention = 50) {
    this.directory = pathInWorkspace(root, workspaceDirectory, true);
    fs.mkdirSync(this.directory, { recursive: true, mode: 0o700 });
    this.jobs = pathInWorkspace(root, path.join(this.directory, "jobs"), true);
    fs.mkdirSync(this.jobs, { recursive: true, mode: 0o700 });
  }

  file(id: string, suffix: ".json" | ".log" | ".cancel" = ".json"): string {
    if (!jobId.test(id)) throw new PluginError("JOB_NOT_FOUND", "Invalid job identifier");
    return pathInWorkspace(this.root, path.join(this.jobs, id + suffix), true);
  }

  get(id: string): JobRecord | undefined {
    try {
      const file = this.file(id);
      if (fs.statSync(file).size > 4 * 1024 * 1024) {
        throw new PluginError("INTERNAL_ERROR", "Persisted job record is oversized");
      }
      const record = readJsonFile(file) as JobRecord;
      if (record.id !== id) throw new PluginError("INTERNAL_ERROR", "Persisted job identifier mismatch");
      return record;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
      throw error;
    }
  }

  list(): JobRecord[] {
    // Job files are authoritative, including after a crash before the index rename.
    return fs.readdirSync(this.jobs).flatMap(file => {
      if (!file.endsWith(".json") || !jobId.test(file.slice(0, -5))) return [];
      const record = this.get(file.slice(0, -5));
      return record ? [record] : [];
    }).sort((a, b) => b.createdAt.localeCompare(a.createdAt) || b.id.localeCompare(a.id));
  }

  resolve(reference: string): JobRecord {
    if (!/^[a-f0-9-]{1,36}$/.test(reference)) throw new PluginError("JOB_NOT_FOUND", "Invalid job reference");
    const matches = this.list().filter(job => job.id.startsWith(reference));
    if (matches.length > 1) throw new PluginError("JOB_AMBIGUOUS", "Use the full job identifier");
    if (!matches.length) throw new PluginError("JOB_NOT_FOUND", "No job matches the supplied reference");
    return matches[0];
  }

  create(record: JobRecord, concurrency: number, check?: (jobs: JobRecord[]) => void): void {
    this.transaction(() => {
      const jobs = this.list();
      const active = jobs.filter(job => isActive(job.state));
      if (active.length >= concurrency) {
        throw new PluginError("CONCURRENCY_LIMIT_REACHED", "Too many active jobs in this workspace", { retryable: true });
      }
      if (record.threadId && active.some(job => job.threadId === record.threadId)) {
        throw new PluginError("CONCURRENCY_LIMIT_REACHED", "A job already owns this Codex thread", { retryable: true });
      }
      if (jobs.some(job => job.id === record.id)) throw new PluginError("INTERNAL_ERROR", "Job identifier already exists");
      check?.(jobs);
      this.persist(record);
      this.pruneAndIndex([record, ...jobs]);
    });
  }

  update(id: string, expected: readonly JobState[], patch: Partial<JobRecord>): JobRecord | undefined {
    return this.transaction(() => {
      const current = this.get(id);
      if (!current || !expected.includes(current.state)) return undefined;
      if (!isActive(current.state) && current.state !== "awaiting_approval") return undefined;
      if (patch.state !== undefined && patch.state !== current.state) assertTransition(current.state, patch.state);
      const job = { ...current, ...patch, id };
      this.persist(job);
      if (job.state !== current.state) this.writeIndex(this.list());
      return job;
    });
  }

  private transaction<T>(operation: () => T): T {
    return withFileLock(path.join(this.directory, ".state.lock"), operation);
  }

  private persist(job: JobRecord): void {
    const sanitized = redact.deep(job);
    // Control identifiers are generated by the plugin and needed for process verification.
    writeJsonFile(this.file(job.id), { ...sanitized, launchToken: job.launchToken, identity: job.identity });
  }

  private writeIndex(jobs: JobRecord[]) {
    writeJsonFile(path.join(this.directory, "state.json"), {
      version: 1, jobs: jobs.map(({ id, state, createdAt }) => ({ id, state, createdAt })),
    });
  }

  private pruneAndIndex(jobs: JobRecord[]) {
    const retained = new Set(jobs.filter(job => !isActive(job.state)).slice(0, this.retention).map(job => job.id));
    const kept: JobRecord[] = [];
    for (const job of jobs) {
      if (retained.has(job.id) || isActive(job.state)) {
        kept.push(job);
      } else {
        for (const suffix of [".json", ".log", ".cancel"] as const) fs.rmSync(this.file(job.id, suffix), { force: true });
      }
    }
    this.writeIndex(kept);
  }
}
